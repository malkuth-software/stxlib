#!/usr/bin/env python3
"""genmc_shim.py GENMC_PTHREAD_H NAMES_FILE > genmc_posix_compat.h

Declares, for libstdc++'s gthr-posix.h under GenMC, the POSIX thread names
it uses that GenMC's runtime pthread.h does not declare (types as glibc
declares them on aarch64; functions as POSIX declares them). Nothing is
defined: a call to one of them reaches GenMC as an undefined external."""
import re
import sys

TYPES = {
    'pthread_key_t': ['typedef unsigned int pthread_key_t;'],
    'pthread_once_t': ['typedef int pthread_once_t;'],
    'pthread_mutexattr_t': ['typedef union { char __size[8]; int __align; } pthread_mutexattr_t;'],
    'pthread_condattr_t': ['typedef union { char __size[8]; int __align; } pthread_condattr_t;'],
    'pthread_cond_t': ['typedef union { char __size[48]; long long __align; } pthread_cond_t;'],
}
MACROS = {
    'PTHREAD_ONCE_INIT': '#define PTHREAD_ONCE_INIT 0',
    'PTHREAD_COND_INITIALIZER': '#define PTHREAD_COND_INITIALIZER { { 0 } }',
    'PTHREAD_MUTEX_RECURSIVE': '#define PTHREAD_MUTEX_RECURSIVE 1',
    'PTHREAD_RECURSIVE_MUTEX_INITIALIZER_NP': '#define PTHREAD_RECURSIVE_MUTEX_INITIALIZER_NP PTHREAD_MUTEX_INITIALIZER',
}
FUNCTIONS = {
    'pthread_once': 'int pthread_once(pthread_once_t*, void (*)(void));',
    'pthread_getspecific': 'void* pthread_getspecific(pthread_key_t);',
    'pthread_setspecific': 'int pthread_setspecific(pthread_key_t, const void*);',
    'pthread_key_create': 'int pthread_key_create(pthread_key_t*, void (*)(void*));',
    'pthread_key_delete': 'int pthread_key_delete(pthread_key_t);',
    'pthread_detach': 'int pthread_detach(pthread_t);',
    'pthread_cancel': 'int pthread_cancel(pthread_t);',
    'pthread_equal': 'int pthread_equal(pthread_t, pthread_t);',
    'pthread_self': 'pthread_t pthread_self(void);',
    'sched_yield': 'int sched_yield(void);',
    'pthread_mutex_timedlock': 'int pthread_mutex_timedlock(pthread_mutex_t*, const struct timespec*);',
    'pthread_mutex_clocklock': 'int pthread_mutex_clocklock(pthread_mutex_t*, clockid_t, const struct timespec*);',
    'pthread_mutexattr_init': 'int pthread_mutexattr_init(pthread_mutexattr_t*);',
    'pthread_mutexattr_settype': 'int pthread_mutexattr_settype(pthread_mutexattr_t*, int);',
    'pthread_mutexattr_destroy': 'int pthread_mutexattr_destroy(pthread_mutexattr_t*);',
    'pthread_cond_init': 'int pthread_cond_init(pthread_cond_t*, const pthread_condattr_t*);',
    'pthread_cond_broadcast': 'int pthread_cond_broadcast(pthread_cond_t*);',
    'pthread_cond_signal': 'int pthread_cond_signal(pthread_cond_t*);',
    'pthread_cond_wait': 'int pthread_cond_wait(pthread_cond_t*, pthread_mutex_t*);',
    'pthread_cond_timedwait': 'int pthread_cond_timedwait(pthread_cond_t*, pthread_mutex_t*, const struct timespec*);',
    'pthread_cond_clockwait': 'int pthread_cond_clockwait(pthread_cond_t*, pthread_mutex_t*, clockid_t, const struct timespec*);',
    'pthread_cond_destroy': 'int pthread_cond_destroy(pthread_cond_t*);',
    'pthread_mutex_init': 'int pthread_mutex_init(pthread_mutex_t*, const pthread_mutexattr_t*);',
    'pthread_mutex_destroy': 'int pthread_mutex_destroy(pthread_mutex_t*);',
    'pthread_mutex_lock': 'int pthread_mutex_lock(pthread_mutex_t*);',
    'pthread_mutex_trylock': 'int pthread_mutex_trylock(pthread_mutex_t*);',
    'pthread_mutex_unlock': 'int pthread_mutex_unlock(pthread_mutex_t*);',
}


def main():
    genmc = open(sys.argv[1], encoding='utf-8').read()
    genmc = re.sub(r'/\*.*?\*/', ' ', genmc, flags=re.S)  # commented-out declarations do not count
    genmc = re.sub(r'//[^\n]*', ' ', genmc)
    used = set(open(sys.argv[2], encoding='utf-8').read().split())
    present = lambda name: re.search(r'\b' + re.escape(name) + r'\b', genmc) is not None
    lines = ['// Generated by proofs/b1/tools/genmc_shim.py: POSIX names libstdc++\'s',
             '// gthr-posix.h uses that GenMC 0.20\'s runtime pthread.h lacks.',
             '#pragma once', '#include <pthread.h>', '#include <time.h>', '#ifdef __cplusplus',
             'extern "C" {', '#endif']
    for name, text in TYPES.items():
        if not present(name):
            lines.extend(text)
    for name, text in MACROS.items():
        if name in used and not present(name):
            lines.append(text)
    for name, text in FUNCTIONS.items():
        if (name in used or name == 'sched_yield') and not present(name):
            lines.append(text)
    lines += ['#ifdef __cplusplus', '}', '#endif']
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
