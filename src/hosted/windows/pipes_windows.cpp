// Anonymous pipes on Windows (include/stxlib/pipes.hpp): CreatePipe,
// ReadFile, WriteFile, DuplicateHandle, SetStdHandle and the C runtime's
// _dup2. Host facts (Microsoft's documentation as published; unconfirmed at
// a pin):
//   - CreatePipe with no security attributes makes handles that are not
//     inherited by children.
//   - ReadFile on an anonymous pipe blocks until data arrives; it fails with
//     ERROR_BROKEN_PIPE once every write handle is closed, which is the end
//     of the stream (as a POSIX read of 0).
//   - WriteFile on a pipe whose read handles are all closed fails with
//     ERROR_NO_DATA (or ERROR_BROKEN_PIPE); no signal exists.
//   - A GUI-subsystem program started with inherited pipe handles as its
//     standard handles reaches them with GetStdHandle and no console window
//     appears (study section 4.1).
//   - Standard output has two names: the process's standard handle
//     (GetStdHandle(STD_OUTPUT_HANDLE), which STXlib's console and the host
//     use) and the C runtime's descriptor 1 (printf). The claim points both
//     at standard error: SetStdHandle for the first, _dup2(2, 1) for the
//     second.
//
// Build note: SetStdHandle is new to STXlib's own Windows API headers
// (src/hosted/windows/api, generated by tools/windows_api_headers from the
// identifiers our sources use); they are regenerated with scan.py and
// generate.py on the Windows builder, which holds the metadata checkout.

