u32 usage_of_code(const u32 code) noexcept {
    if (code >= evdev_code_count) return 0U;
    const u32 result = usage_by_code[code];
    return result;
}

u8 modifier_of_usage(const u32 usage) noexcept {
    switch (usage) {
    case 0xE0U:
    case 0xE4U:
        return modifier_control;
    case 0xE1U:
    case 0xE5U:
        return modifier_shift;
    case 0xE2U:
    case 0xE6U:
        return modifier_alt;
    case 0xE3U:
    case 0xE7U:
        return modifier_meta;
    default:
        return 0U;
    }
}

char text_of_usage(const u32 usage, const u8 modifiers, const bool caps_lock, const bool num_lock) noexcept {
    const u8 shortcut = static_cast<u8>(modifier_control | modifier_alt | modifier_meta);
    if ((modifiers & shortcut) != 0U) return 0;
    const bool shift = (modifiers & modifier_shift) != 0U;
    if (usage >= 0x04U && usage <= 0x1DU) {
        const bool upper = shift != caps_lock;
        const char base = upper ? 'A' : 'a';
        const char result = static_cast<char>(base + static_cast<char>(usage - 0x04U));
        return result;
    }
    if (usage >= 0x1EU && usage <= 0x38U) {
        const char result = shift ? row_shifted[usage - 0x1EU] : row_plain[usage - 0x1EU];
        return result;
    }
    switch (usage) {
    case 0x54U:
        return '/';
    case 0x55U:
        return '*';
    case 0x56U:
        return '-';
    case 0x57U:
        return '+';
    case 0x64U: // the ISO key beside the left Shift: backslash on the US layout
        return shift ? '|' : '\\';
    case 0x67U:
        return '=';
    default:
        break;
    }
    if (usage >= 0x59U && usage <= 0x63U && num_lock) {
        const char result = keypad_digits[usage - 0x59U];
        return result;
    }
    return 0;
}

