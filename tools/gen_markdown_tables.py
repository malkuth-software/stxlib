#!/usr/bin/env python3
"""Generates the tables of stxlib::markdown (src/algorithms/markdown/*.inc).

Inputs, all pinned in PROVENANCE.md:
  third_party/unicode-18.0.0/UnicodeData.txt   general categories
  third_party/unicode-18.0.0/CaseFolding.txt   full case folding (status C and F)
  third_party/whatwg-entities/entities.json    the HTML named character references

Outputs:
  unicode_classes.inc     whitespace_ranges (general category Zs) and
                          punctuation_ranges (general categories P* and S*,
                          CommonMark 0.31.2's "Unicode punctuation"), above
                          U+007F, as sorted, disjoint, inclusive ranges.
  case_folding_full.inc   full_foldings: every code point above U+007F whose
                          full folding is not itself, with its one to three
                          folded code points, sorted by code point.
  entities_table.inc      entity_names (every name end to end) and entities
                          (offset, length, one or two code points), sorted by
                          name byte-wise. Only the names written with their
                          ';' are taken: CommonMark requires it.

Each table's stated properties are checked before anything is written; a
failed check stops with a message and writes nothing.

Usage: python3 -I tools/gen_markdown_tables.py [--check]
--check compares what would be written with the files present and fails if
they differ (for a test).
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
UNICODE = ROOT / 'third_party' / 'unicode-18.0.0'
ENTITIES = ROOT / 'third_party' / 'whatwg-entities' / 'entities.json'
OUT = ROOT / 'src' / 'algorithms' / 'markdown'

LONGEST_ENTITY_NAME = 31  # entities.hpp, longest_entity_name


def stop(message: str) -> None:
    print(f'gen_markdown_tables: {message}', file=sys.stderr)
    sys.exit(1)


def general_categories() -> dict[int, str]:
    """Code point -> general category, for every assigned code point."""
    categories: dict[int, str] = {}
    range_first: int = -1
    for line in (UNICODE / 'UnicodeData.txt').read_text(encoding='utf-8').splitlines():
        fields: list[str] = line.split(';')
        if len(fields) < 3:
            continue
        code_point: int = int(fields[0], 16)
        name: str = fields[1]
        category: str = fields[2]
        if name.endswith(', First>'):
            range_first = code_point
            continue
        if name.endswith(', Last>'):
            if range_first < 0:
                stop(f'a range end without its start at {fields[0]}')
            for inside in range(range_first, code_point + 1):
                categories[inside] = category
            range_first = -1
            continue
        categories[code_point] = category
    return categories


def ranges_of(code_points: list[int]) -> list[tuple[int, int]]:
    """Sorted code points as maximal inclusive ranges."""
    ranges: list[tuple[int, int]] = []
    for code_point in sorted(code_points):
        if ranges and ranges[-1][1] + 1 == code_point:
            ranges[-1] = (ranges[-1][0], code_point)
        else:
            ranges.append((code_point, code_point))
    return ranges


def unicode_classes() -> str:
    categories: dict[int, str] = general_categories()
    whitespace: list[int] = [cp for cp, category in categories.items() if cp > 0x7f and category == 'Zs']
    punctuation: list[int] = [cp for cp, category in categories.items() if cp > 0x7f and category[0] in 'PS']
    # ASCII is decided by the byte table; check that it agrees with the file.
    for cp in range(0x80):
        is_punctuation: bool = categories[cp][0] in 'PS'
        in_table: bool = (33 <= cp <= 47) or (58 <= cp <= 64) or (91 <= cp <= 96) or (123 <= cp <= 126)
        if is_punctuation != in_table:
            stop(f'ASCII punctuation disagrees with UnicodeData.txt at U+{cp:04X}')
        if (categories[cp] == 'Zs') != (cp == 0x20):
            stop(f'ASCII Zs disagrees with UnicodeData.txt at U+{cp:04X}')
    lines: list[str] = ['// Generated by tools/gen_markdown_tables.py from UnicodeData.txt 18.0.0. Do not edit.', '']
    for name, points in (('whitespace_ranges', whitespace), ('punctuation_ranges', punctuation)):
        ranges: list[tuple[int, int]] = ranges_of(points)
        for index in range(1, len(ranges)):
            if ranges[index][0] <= ranges[index - 1][1] + 1:
                stop(f'{name} is not sorted and disjoint')
        lines.append(f'// {len(points)} code points in {len(ranges)} ranges.')
        lines.append(f'inline constexpr CodePointRange {name}[] = {{')
        for first, last in ranges:
            lines.append(f'    {{0x{first:04X}, 0x{last:04X}}},')
        lines.append('};')
        lines.append('')
    return '\n'.join(lines)


def case_folding_full() -> str:
    foldings: dict[int, list[int]] = {}
    for line in (UNICODE / 'CaseFolding.txt').read_text(encoding='utf-8').splitlines():
        text: str = line.split('#', 1)[0].strip()
        if not text:
            continue
        fields: list[str] = [field.strip() for field in text.split(';')]
        if len(fields) < 3 or fields[1] not in ('C', 'F'):
            continue
        code_point: int = int(fields[0], 16)
        mapped: list[int] = [int(piece, 16) for piece in fields[2].split()]
        if code_point in foldings:
            stop(f'two full foldings for U+{code_point:04X}')
        foldings[code_point] = mapped
    for cp in range(0x80):
        expected: list[int] = [cp + 32] if 0x41 <= cp <= 0x5a else []
        if foldings.get(cp, []) != expected:
            stop(f'ASCII folding is not A-Z to a-z at U+{cp:04X}')
    entries: list[tuple[int, list[int]]] = sorted((cp, mapped) for cp, mapped in foldings.items() if cp > 0x7f)
    longest: int = max(len(mapped) for _, mapped in entries)
    if longest > 3:
        stop(f'a full folding of {longest} code points; the reader allows 3')
    for cp, mapped in entries:
        if any(piece > 0x10ffff or 0xd800 <= piece <= 0xdfff or piece == 0 for piece in mapped):
            stop(f'U+{cp:04X} folds to something that is not a scalar value')
    lines: list[str] = ['// Generated by tools/gen_markdown_tables.py from CaseFolding.txt 18.0.0 (status C and F).',
                        '// Do not edit.', '',
                        f'// {len(entries)} code points; at most {longest} folded code points each.',
                        'inline constexpr FullFolding full_foldings[] = {']
    for cp, mapped in entries:
        padded: list[int] = mapped + [0] * (3 - len(mapped))
        lines.append(f'    {{0x{cp:04X}, {len(mapped)}, {{0x{padded[0]:04X}, 0x{padded[1]:04X}, 0x{padded[2]:04X}}}}},')
    lines.append('};')
    lines.append('')
    return '\n'.join(lines)


def entities_table() -> str:
    data: dict[str, dict[str, list[int]]] = json.loads(ENTITIES.read_text(encoding='utf-8'))
    named: list[tuple[bytes, list[int]]] = []
    for key, value in data.items():
        if not key.startswith('&'):
            stop(f'an entity key without "&": {key!r}')
        if not key.endswith(';'):
            continue
        name: bytes = key[1:-1].encode('ascii')
        code_points: list[int] = value['codepoints']
        if not name or not name[:1].isalpha() or not name.isalnum():
            stop(f'a name that is not a letter followed by letters and digits: {key!r}')
        if len(name) > LONGEST_ENTITY_NAME:
            stop(f'{key!r} is longer than {LONGEST_ENTITY_NAME} bytes (entities.hpp)')
        if not 1 <= len(code_points) <= 2 or any(cp == 0 or cp > 0x10ffff for cp in code_points):
            stop(f'{key!r} does not have one or two code points')
        named.append((name, code_points))
    named.sort()
    for index in range(1, len(named)):
        if named[index][0] == named[index - 1][0]:
            stop(f'a name twice: {named[index][0]!r}')
    longest: int = max(len(name) for name, _ in named)
    if longest != LONGEST_ENTITY_NAME:
        stop(f'the longest name is {longest} bytes; entities.hpp says {LONGEST_ENTITY_NAME}')
    blob: bytes = b''.join(name for name, _ in named)
    lines: list[str] = ['// Generated by tools/gen_markdown_tables.py from the WHATWG entities.json. Do not edit.', '',
                        f'// {len(named)} names, {len(blob)} bytes.',
                        'inline constexpr char entity_names[] =']
    for start in range(0, len(blob), 96):
        lines.append('    "' + blob[start:start + 96].decode('ascii') + '"')
    lines[-1] += ';'
    lines.append('')
    lines.append('inline constexpr NamedReference entities[] = {')
    offset: int = 0
    for name, code_points in named:
        second: int = code_points[1] if len(code_points) == 2 else 0
        lines.append(f'    {{{offset}, {len(name)}, 0x{code_points[0]:04X}, 0x{second:04X}}}, // {name.decode("ascii")}')
        offset += len(name)
    lines.append('};')
    lines.append('')
    return '\n'.join(lines)


def main() -> int:
    check: bool = sys.argv[1:] == ['--check']
    if sys.argv[1:] and not check:
        stop('usage: gen_markdown_tables.py [--check]')
    outputs: dict[str, str] = {
        'unicode_classes.inc': unicode_classes(),
        'case_folding_full.inc': case_folding_full(),
        'entities_table.inc': entities_table(),
    }
    differs: bool = False
    for name, text in outputs.items():
        path: pathlib.Path = OUT / name
        if check:
            if not path.is_file() or path.read_text(encoding='utf-8') != text:
                print(f'{name}: differs from what the inputs give')
                differs = True
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print(f'{name}: {len(text.splitlines())} lines')
    return 1 if differs else 0


if __name__ == '__main__':
    sys.exit(main())
