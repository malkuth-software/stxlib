#!/usr/bin/env python3
"""Writes src/algorithms/glyphs/hinter_tables.inc from Skrifa's table of scripts.

The input is skrifa-0.50.0/generated/generated_autohint_styles.rs as published in the skrifa
0.50.0 crate (PROVENANCE.md: stxlib::glyphs, the hinter). It is not in this tree: the table
is regenerated only when a later Skrifa is taken, by running this with the file's path.

    python3 -I tools/gen_hinter_tables.py <generated_autohint_styles.rs> <hinter_tables.inc>
"""
import hashlib
import re
import sys

PINNED_SHA256 = "94268a720cd802ac02b74eae0d955f62427f2a10409a5536a724ef1494151982"

ZONES = {"NONE": 0, "TOP": 2, "SUB_TOP": 4, "NEUTRAL": 8, "ADJUSTMENT": 16, "X_HEIGHT": 32, "LONG": 64,
         "HORIZONTAL": 4, "RIGHT": 2}
GROUPS = {"Default": 0, "Cjk": 1, "Indic": 2}


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED_SHA256:
        sys.stderr.write("gen_hinter_tables: the input is not the pinned file (%s)\n" % digest)
        return 1
    text = data.decode("utf-8")
    scripts_text = text[text.index("pub const SCRIPT_CLASSES"):text.index("impl StyleClass")] if "impl StyleClass" in text else text
    styles_text = text[text.index("pub const STYLE_CLASSES"):text.index("const STYLE_RANGES")]
    ranges_text = text[text.index("const STYLE_RANGES"):]
    characters = []
    blues = []
    scripts = []

    def put(string):
        first = len(characters)
        characters.extend(ord(c) for c in string)
        return first, len(string)

    script_pattern = re.compile(
        r'ScriptClass \{\s*name: "([^"]*)",\s*group: ScriptGroup::(\w+),\s*tag: [^\n]*\n\s*hint_top_to_bottom: (\w+),\s*'
        r'std_chars: "([^"]*)",\s*blues: &\[(.*?)\],\s*\},', re.S)
    blue_pattern = re.compile(r'\("([^"]*)", ([^\n]*)\),')
    for name, group, top_to_bottom, standard, blue_block in script_pattern.findall(scripts_text):
        standard_first, standard_count = put(standard)
        blue_first = len(blues)
        for string, zones_text in blue_pattern.findall(blue_block):
            zones = 0
            for zone in re.findall(r"BlueZones::(\w+)", zones_text):
                zones |= ZONES[zone]
            first, count = put(string)
            blues.append((first, count, zones))
        scripts.append((name, GROUPS[group], top_to_bottom == "true", standard_first, standard_count, blue_first, len(blues) - blue_first))
    styles = []
    for name, index, script, feature in re.findall(
            r'StyleClass \{ name: "([^"]*)", index: (\d+), script: &SCRIPT_CLASSES\[(\d+)\], feature: (None|Some)', styles_text):
        assert int(index) == len(styles)
        styles.append((name, int(script), feature == "Some"))
    ranges = [(int(first), int(last), int(style), non == "non_")
              for non, first, last, style in re.findall(r"(non_)?base_range\((\d+), (\d+), (\d+)\)", ranges_text)]
    assert ranges == sorted(ranges, key=lambda entry: entry[0])
    latin = next(i for i, style in enumerate(styles) if style[0] == "Latin")
    han = next(i for i, style in enumerate(styles) if style[0] == "CJKV ideographs")
    out = []
    out.append("// Generated by tools/gen_hinter_tables.py from Skrifa 0.50.0's")
    out.append("// generated/generated_autohint_styles.rs (SHA-256 %s)." % digest)
    out.append("// Do not edit: %d scripts, %d styles, %d ranges of characters." % (len(scripts), len(styles), len(ranges)))
    out.append("")
    out.append("inline constexpr usize table_latin_style = %d;" % latin)
    out.append("inline constexpr usize table_han_style = %d;" % han)
    out.append("")
    out.append("inline constexpr u32 table_characters[] = {")
    for start in range(0, len(characters), 12):
        out.append("    " + " ".join("0x%X," % c for c in characters[start:start + 12]))
    out.append("};")
    out.append("")
    out.append("// first character, count, zones")
    out.append("inline constexpr TableBlue table_blues[] = {")
    for first, count, zones in blues:
        out.append("    {%d, %d, %d}," % (first, count, zones))
    out.append("};")
    out.append("")
    out.append("// group, top to bottom, standard characters (first, count), blues (first, count)")
    out.append("inline constexpr TableScript table_scripts[] = {")
    for name, group, top_to_bottom, standard_first, standard_count, blue_first, blue_count in scripts:
        out.append("    {%d, %s, %d, %d, %d, %d}, // %s" % (group, "true" if top_to_bottom else "false", standard_first, standard_count,
                                                             blue_first, blue_count, name))
    out.append("};")
    out.append("")
    out.append("// script, whether it is for a layout feature")
    out.append("inline constexpr TableStyle table_styles[] = {")
    for name, script, feature in styles:
        out.append("    {%d, %s}, // %s" % (script, "true" if feature else "false", name))
    out.append("};")
    out.append("")
    out.append("// first character, last, style, whether its characters are marks")
    out.append("inline constexpr TableRange table_ranges[] = {")
    for first, last, style, non_base in ranges:
        out.append("    {0x%X, 0x%X, %d, %s}," % (first, last, style, "true" if non_base else "false"))
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print("scripts %d, blues %d, styles %d, ranges %d, characters %d, latin %d, han %d, sha256 %s" %
          (len(scripts), len(blues), len(styles), len(ranges), len(characters), latin, han, digest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
