#!/usr/bin/env python3
"""Split the half-turn derivatives of the certified sincos anchors."""
import re
from fractions import Fraction
from pathlib import Path

from sincos_certificate import PI_LOW, PI_HIGH

root = Path(__file__).resolve().parents[2] / "src/algorithms/math"
pi = (PI_LOW + PI_HIGH) / 2
table = (root / "sincos_table256.hpp").read_text()
rows = re.findall(r"^    \{([^{}]+)\},?", table, re.M)
assert len(rows) == 256
output = ["// Generated by tools/math/gen_pi_slopes.py."]
for row in rows:
    s, c, s_lo, c_lo = [Fraction(float.fromhex(x)) for x in row.split(",")]
    parts = []
    for v, bits in ((s + s_lo, 52), (c + c_lo, 52),
                    (pi * (c + c_lo), 22), (-pi * (s + s_lo), 22)):
        hi = Fraction(round(v * (1 << bits)), 1 << bits)
        parts.extend([float(hi).hex(), float(v - hi).hex()])
    output.append("    {" + ", ".join(parts) + "},")
(root / "pi_slopes.inc").write_text("\n".join(output) + "\n")
