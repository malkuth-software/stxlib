#!/usr/bin/env python3
"""Generate the Gaussian survival grid with decimal arithmetic, from the far tail inward."""
from decimal import Decimal, localcontext
from pathlib import Path
from sincos_certificate import PI_LOW, PI_HIGH

ROOT = Path(__file__).resolve().parents[2]
with localcontext() as context:
    context.prec = 85
    pi_mid = (PI_LOW + PI_HIGH) / 2
    pi = Decimal(pi_mid.numerator) / Decimal(pi_mid.denominator)
    density_at_zero = 1 / (2 * pi).sqrt()
    step = Decimal(1) / 32
    rows = []
    tail_rows = []
    # Q(39) < phi(39)/39 < 2^-1100, below half a subnormal ulp.
    tail = Decimal(0)
    for index in reversed(range(39 * 32 + 1)):
        centre = index * step
        previous = Decimal(0)
        density = density_at_zero * (-centre * centre / 2).exp()
        coefficients = []
        area = Decimal(0)
        power = step
        # Integrate phi(centre-t) back to the preceding node. The series
        # follows f'=(centre-t)f. The last term at 39 is below 10^-90
        # relative with this many terms.
        for order in range(80):
            term = density / (order + 1)
            if order < 15:
                coefficients.append(term if order % 2 else -term)
            area += term * power
            power *= step
            previous, density = density, (centre * density - previous) / (order + 1)
        rows.append('    {' + ', '.join(float(x).hex() for x in [tail, *coefficients[:7]]) + '},')
        if index >= 8 * 32:
            tail_rows.append('    {' + ', '.join(float(x).hex() for x in coefficients[7:]) + '},')
        tail += area
    out = ROOT / 'src/algorithms/math/gaussian_table.inc'
    out.write_text('// Generated by tools/math/gen_gaussian_table.py.\n' + '\n'.join(reversed(rows)) + '\n')
    extra = out.with_name('gaussian_tail_terms.inc')
    extra.write_text('// Generated by tools/math/gen_gaussian_table.py.\n' + '\n'.join(reversed(tail_rows)) + '\n')
