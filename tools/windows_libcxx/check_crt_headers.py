#!/usr/bin/env python3
"""Check STXlib's UCRT headers against ucrtbase.dll's exports and write the
import list.

Every function a header in src/hosted/windows/crt/include declares with
_STXLIB_UCRT must be exported by ucrtbase.dll (the snapshot
src/hosted/windows/crt/ucrtbase_exports.txt, taken with
`llvm-readobj --coff-exports C:/Windows/System32/ucrtbase.dll`), and
src/hosted/windows/crt/ucrtbase.def must list exactly those functions.

  check_crt_headers.py            check; exit 1 on any finding
  check_crt_headers.py --write    rewrite ucrtbase.def from the headers

The import list is the set the headers declare, not the set a given build
calls: an import library only contributes the members a link references, so
a declared but uncalled function costs nothing in an image.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRT = ROOT / "src" / "hosted" / "windows" / "crt"
INCLUDE = CRT / "include"
EXPORTS = CRT / "ucrtbase_exports.txt"
DEF = CRT / "ucrtbase.def"

# A declaration: _STXLIB_UCRT, then the return type and attributes, then the
# name directly before its parameter list.
DECLARATION = re.compile(r"_STXLIB_UCRT\b[^;{]*?\b([A-Za-z_][A-Za-z0-9_]*)\s*\(", re.S)

DEF_HEADER = (
    "; ucrtbase.dll's exports that STXlib's C library headers declare\n"
    "; (src/hosted/windows/crt/include). Generated by\n"
    "; tools/windows_libcxx/check_crt_headers.py --write; do not edit.\n"
    "; Import library: llvm-dlltool -m i386:x86-64 -d ucrtbase.def -l ucrtbase.lib\n"
    "LIBRARY ucrtbase.dll\n"
    "EXPORTS\n"
)


def declared_imports() -> dict:
    found = {}
    for header in sorted(INCLUDE.rglob("*.h")):
        text = header.read_text(encoding="utf-8")
        # Drop comments and the macro's own definition line.
        text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
        text = re.sub(r"//[^\n]*", "", text)
        text = re.sub(r"#define _STXLIB_UCRT[^\n]*", "", text)
        for match in DECLARATION.finditer(text):
            name = match.group(1)
            found.setdefault(name, header.relative_to(INCLUDE).as_posix())
    return found


def main() -> int:
    write = "--write" in sys.argv[1:]
    exports = {line.strip() for line in EXPORTS.read_text(encoding="utf-8").splitlines() if line.strip() and not line.startswith("#")}
    imports = declared_imports()
    findings = []
    for name, header in sorted(imports.items()):
        if name not in exports:
            findings.append(f"{header}: {name} is not exported by ucrtbase.dll")
    expected = DEF_HEADER + "".join(f"    {name}\n" for name in sorted(imports))
    if write:
        DEF.write_text(expected, encoding="utf-8", newline="\n")
    else:
        current = DEF.read_text(encoding="utf-8") if DEF.exists() else ""
        if current.replace("\r\n", "\n") != expected:
            findings.append("ucrtbase.def differs from the headers (run with --write)")
    for finding in findings:
        print(finding)
    print(f"check_crt_headers: {len(imports)} imports, {len(findings)} findings")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
